"""Generate rl/workplace_env_tools.py: one explicit method per workplace tool.

TRL's `environment_factory` builds the model-facing tool schemas from each public method's
signature, type hints and Google-style docstring, so we emit real methods (not dynamic ones)
from the original NeMo Gym schemas. Re-run after changing the schemas:

    python -m rl.gen_workplace_env
"""
import os

from rl.workplace_assistant.utils import get_tools

TOOLKITS = ["email", "calendar", "analytics", "project_management", "customer_relationship_manager"]
PYTYPE = {"string": "str", "integer": "int"}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "workplace_env_tools.py")


def one_line(text: str) -> str:
    text = " ".join(str(text).split())
    assert '"""' not in text and "\\" not in text, text
    return text


def emit_method(schema: dict) -> str:
    props = schema["parameters"]["properties"]
    required = set(schema["parameters"].get("required", []))
    # Required params first (no default), then optional ones (default None).
    order = [p for p in props if p in required] + [p for p in props if p not in required]
    sig = ["self"]
    for p in order:
        t = PYTYPE[props[p]["type"]]
        sig.append(f"{p}: {t}" if p in required else f"{p}: Optional[{t}] = None")
    lines = [f"    def {schema['name']}({', '.join(sig)}) -> str:", f'        """{one_line(schema["description"])}']
    if order:
        lines += ["", "        Args:"]
        for p in order:
            lines.append(f"            {p}: {one_line(props[p].get('description', p))}")
    lines += ["", "        Returns:", "            The tool result as text.", '        """']
    call_args = ", ".join(f"{p}={p}" for p in order)
    lines.append(f'        return self._call("{schema["name"]}"{", " + call_args if call_args else ""})')
    return "\n".join(lines)


def main():
    schemas = get_tools(TOOLKITS)["schemas"]
    header = '''# AUTO-GENERATED by rl/gen_workplace_env.py from the NVIDIA NeMo Gym workplace_assistant
# schemas (Apache-2.0, see rl/NOTICE.md). Do not edit by hand; re-run the generator.
from typing import Optional


class WorkplaceTools:
    """Mixin: the 27 workplace tools. Requires `self._call(name, **kwargs) -> str`."""

'''
    body = "\n\n".join(emit_method(s) for s in schemas)
    with open(OUT, "w") as f:
        f.write(header + body + "\n")
    print(f"wrote {len(schemas)} methods -> {OUT}")


if __name__ == "__main__":
    main()
